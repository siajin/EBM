def clean(s):
    for a,b in replacements.items():
        s = s.replace(a,b)
    s = re.sub(r'\bTrain\b', '학습 자료', s)
    s = re.sub(r'\bTrain(?=\d)', '학습 자료 ', s)
    s = re.sub(r'\bmetadata\b', '메타데이터', s)
    s = re.sub(r'\bpilot\b', '진단 표본', s)
    s = re.sub(r'\bseed\s*(\d+)', r'seed \1', s)
    s = re.sub(r'\blr(1e-\d)', r'학습률 \1', s)
    s = re.sub(r'\bcommit(?=[0-9a-f])', 'commit ', s)
    s = re.sub(r'(19LA|21LA|21DF|EER|DF|학습 자료)(?=\d)', r'\1 ', s)
    s = re.sub(r'(?<=\d)\s+%', '%', s)
    s = re.sub(r'(?<=\d)\s+°', '°', s)
    s = re.sub(r'(?<=\d)\s+(이다|다|이면|이며|였다|에서|으로|보다|에|만|까지)(?=\s|[.,;])', r'\1', s)
    s = re.sub(r'(epoch)\s+(마다|부터|당|이하|이상|에서)', r'\1\2', s)
    s = re.sub(r'\b(K|N|k) 개', r'\1개', s)
    s = re.sub(r'([.,])(?=[가-힣A-Z])', r'\1 ', s)
    s = re.sub(r'\s+([·/])\s*', r'\1', s)
    return s

